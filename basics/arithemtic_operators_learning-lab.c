# include <stdio.h>

int main(void) {
    int x = 10;
    int y = 3;
    int z = 5;
    
    printf("%d\n", x + y);
    printf("%d\n", x - y);
    printf("%d\n", x * y);
    printf("%d\n", x / y);
    printf("%d\n", x % y);
    printf("%d\n", ++z);
    printf("%d\n", --z);

    return 0;
}
